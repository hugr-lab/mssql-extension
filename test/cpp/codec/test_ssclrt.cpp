//! A little-endian builder for hand-made values.
struct Bytes {
	std::vector<uint8_t> b;
	Bytes &U8(uint8_t v) {
		b.push_back(v);
		return *this;
	}
	Bytes &U32(uint32_t v) {
		for (int i = 0; i < 4; i++) {
			b.push_back(static_cast<uint8_t>(v >> (8 * i)));
		}
		return *this;
	}
	Bytes &I32(int32_t v) {
		return U32(static_cast<uint32_t>(v));
	}
	Bytes &F64(double d) {
		uint64_t bits;
		std::memcpy(&bits, &d, 8);
		for (int i = 0; i < 8; i++) {
			b.push_back(static_cast<uint8_t>(bits >> (8 * i)));
		}
		return *this;
	}
	//! SRID 0, the version, the properties.
	Bytes &Header(uint8_t version, uint8_t properties) {
		return U32(0).U8(version).U8(properties);
	}
	Bytes &Figure(uint8_t attribute, uint32_t first_point) {
		return U8(attribute).U32(first_point);
	}
	Bytes &Shape(int32_t parent, int32_t figure, uint8_t type) {
		return I32(parent).I32(figure).U8(type);
	}
};

//! `depth` collections nested in each other around one point.
std::vector<uint8_t> Nested(uint32_t depth) {
	Bytes v;
	v.Header(1, 0x04).U32(1).F64(1).F64(2).U32(1).Figure(1, 0).U32(depth + 1);
	for (uint32_t d = 0; d < depth; d++) {
		v.Shape(static_cast<int32_t>(d) - 1, 0, 7);
	}
	v.Shape(static_cast<int32_t>(depth) - 1, 0, 1);
	return v.b;
}

void Refused(const std::vector<uint8_t> &b, SpatialStatus want, const std::string &what) {
	std::string out = "keep";
	const auto got = ToWkb(b.data(), b.size(), false, true, out);
	Check(got == want && out == "keep", what + ": " + StatusName(got));
}

