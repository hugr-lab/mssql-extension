int failures = 0;

void Check(bool ok, const std::string &what) {
	std::cout << (ok ? "  ok   " : "  FAIL ") << what << std::endl;
	if (!ok) {
		failures++;
	}
}

std::vector<uint8_t> FromHex(const std::string &h) {
	std::vector<uint8_t> b;
	for (size_t i = 0; i + 1 < h.size(); i += 2) {
		b.push_back(static_cast<uint8_t>(std::stoi(h.substr(i, 2), nullptr, 16)));
	}
	return b;
}

std::string ToHex(const std::string &b) {
	static const char *digits = "0123456789ABCDEF";
	std::string h;
	for (unsigned char c : b) {
		h += digits[c >> 4];
		h += digits[c & 15];
	}
	return h;
}

const char *StatusName(SpatialStatus s) {
	return duckdb::mssql::codec::ssclrt::DescribeStatus(s);
}

SpatialStatus Decode(const std::vector<uint8_t> &b, bool geography, bool curves, std::string &out) {
	out.clear();
	return ToWkb(b.data(), b.size(), geography, curves, out);
}

