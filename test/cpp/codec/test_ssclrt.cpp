ColumnMetadata SpatialColumn(const std::string &name, const std::string &type, GeometryAs as) {
	ColumnMetadata c{};
	c.name = name;
	c.type_id = duckdb::tds::TDS_TYPE_UDT;
	c.max_length = 0xFFFF;
	c.flags = 0x01;	 // nullable
	c.udt_schema = "sys";
	c.udt_type_name = type;
	c.geometry_as = as;
	return c;
}

//! A UDT value as the row carries it: PLP (G2), a u64 total, one chunk, the terminator; NULL as PLP_NULL.
void AppendPlp(std::vector<uint8_t> &row, const std::vector<uint8_t> *value) {
	auto put = [&row](uint64_t v, int bytes) {
		for (int i = 0; i < bytes; i++) {
			row.push_back(static_cast<uint8_t>(v >> (8 * i)));
		}
	};
	if (!value) {
		put(~uint64_t(0), 8);
		return;
	}
	put(value->size(), 8);
	if (!value->empty()) {
		put(value->size(), 4);
		row.insert(row.end(), value->begin(), value->end());
	}
	put(0, 4);
}

//! The last Stage's spatial counts.
duckdb::mssql::codec::spatial::SpatialColumnNotes last_notes;

//! Stage `values` (nullptr = NULL) as one column into a vector of `type`; the values a GEOMETRY cannot
//! hold beside (out_of_range), and every count in last_notes.
std::vector<std::string> Stage(const ColumnMetadata &column, const LogicalType &type,
							   const std::vector<const std::vector<uint8_t> *> &values, idx_t &out_of_range,
							   bool &constant) {
	std::vector<ColumnMetadata> columns = {column};
	duckdb::DataChunk chunk;
	chunk.Initialize(duckdb::Allocator::DefaultAllocator(), {type});
	std::vector<duckdb::Vector *> targets = {&chunk.data[0]};
	duckdb::mssql::codec::staging::RowStager stager;
	stager.Configure(columns, targets);
	stager.BeginChunk(targets);
	for (idx_t r = 0; r < values.size(); r++) {
		std::vector<uint8_t> row;
		AppendPlp(row, values[r]);
		stager.StageRow(row.data(), row.size(), r);
	}
	stager.FinalizeChunk(values.size());
	chunk.SetChildCardinality(values.size());
	last_notes = stager.SpatialNotes(0);
	out_of_range = last_notes.not_geometry;
	constant = chunk.data[0].GetVectorType() == duckdb::VectorType::CONSTANT_VECTOR;
	std::vector<std::string> got;
	for (idx_t r = 0; r < values.size(); r++) {
		const auto v = chunk.data[0].GetValue(r);
		if (v.IsNull()) {
			got.push_back("NULL");
		} else {
			const auto &s = duckdb::StringValue::Get(v);
			got.push_back(ToHex(s));
		}
	}
	return got;
}

