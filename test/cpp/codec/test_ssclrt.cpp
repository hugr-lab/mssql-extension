void TestServerValues() {
	std::cout << "G1: the server's stored values against its AsBinaryZM()" << std::endl;
	int geometry_ok = 0, wkb_ok = 0, duckdb_ok = 0, curves = 0;
	duckdb::StringHeap heap;
	for (const auto &v : G1) {
		const auto stored = FromHex(v.stored);
		std::string out;
		// geometry_as 'wkb': every value, the curves and FullGlobe in their ISO forms.
		const auto wkb_status = Decode(stored, v.geography, true, out);
		if (wkb_status == SpatialStatus::Ok && ToHex(out) == v.wkb) {
			wkb_ok++;
		} else {
			std::cout << "    wkb " << v.name << ": " << StatusName(wkb_status) << " " << ToHex(out) << "\n      want "
					  << v.wkb << std::endl;
		}
		// geometry_as 'geometry': the same bytes, or NotGeometry for a curve with nothing written.
		const auto geometry_status = Decode(stored, v.geography, false, out);
		if (v.curve) {
			curves++;
			if (geometry_status == SpatialStatus::NotGeometry && out.empty()) {
				geometry_ok++;
			} else {
				std::cout << "    geometry " << v.name << ": " << StatusName(geometry_status) << std::endl;
			}
			continue;
		}
		if (geometry_status == SpatialStatus::Ok && ToHex(out) == v.wkb) {
			geometry_ok++;
		} else {
			std::cout << "    geometry " << v.name << ": " << StatusName(geometry_status) << std::endl;
		}
		// What the kernel writes into a GEOMETRY vector is a GEOMETRY DuckDB's own reader takes as it is.
		duckdb::string_t result;
		bool taken = false;
		try {
			taken = duckdb::Geometry::FromBinary(duckdb::string_t(out.data(), static_cast<uint32_t>(out.size())),
												 result, heap, true);
		} catch (std::exception &e) {
			std::cout << "    duckdb " << v.name << ": " << e.what() << std::endl;
		}
		if (taken && std::string(result.GetData(), result.GetSize()) == out) {
			duckdb_ok++;
		} else if (taken) {
			std::cout << "    duckdb " << v.name << ": rewritten" << std::endl;
		}
	}
	const int count = static_cast<int>(sizeof(G1) / sizeof(G1[0]));
	Check(wkb_ok == count, "geometry_as 'wkb': " + std::to_string(wkb_ok) + " of " + std::to_string(count) +
							   " values give the server's WKB (POINT EMPTY as DuckDB's)");
	Check(geometry_ok == count, "geometry_as 'geometry': " + std::to_string(geometry_ok) + " of " +
									std::to_string(count) + ", " + std::to_string(curves) +
									" curves / FullGlobe NotGeometry");
	Check(duckdb_ok == count - curves, "DuckDB's GEOMETRY takes " + std::to_string(duckdb_ok) + " of " +
										   std::to_string(count - curves) +
										   " outputs unchanged (little-endian ISO WKB is its storage)");
	Check(curves == 11, "11 curve / FullGlobe values among them");
}

