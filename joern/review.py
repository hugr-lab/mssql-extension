#!/usr/bin/env python3
"""Turn a Joern scan report into a review worklist.

A raw report is a few hundred lines of file:line, which is not something a
person can sit down and review. The same report grouped by query, then by file,
then by the *shape* of the expression, is: twenty `1 + data_length` hits in one
row reader are one question asked twenty times, not twenty questions.

    joern/review.py                      # joern/out/report-tds.md  -> review-tds.md
    joern/review.py joern/out/report-all.md

q1 and q9 are inventories (a list of methods, by design), so they are summarised
by file instead of itemised.
"""
import re
import sys
from collections import OrderedDict
from pathlib import Path

HIT = re.compile(r"^\s{4}(\S+?):(\d+|\?)\s{2,}(.*)$")
HEAD = re.compile(r"^## (q\d+) — (.*)$")
INVENTORY = {"q1", "q9"}


def normalise(payload: str) -> str:
    """The shape of a hit: numbers and type annotations collapsed away."""
    s = re.sub(r"\s*\[[^\]]*\]\s*$", "", payload)          # [operand:type] suffix
    s = re.sub(r"\b\d+\b", "N", s)                          # 1 + len == 2 + len
    s = re.sub(r"\s+", " ", s).strip()
    return s


def parse(path: Path):
    queries = OrderedDict()
    current = None
    for line in path.read_text().splitlines():
        head = HEAD.match(line)
        if head:
            current = head.group(1)
            queries[current] = {"title": head.group(2), "hits": []}
            continue
        hit = HIT.match(line)
        if hit and current:
            f, ln, payload = hit.groups()
            queries[current]["hits"].append((f, ln, payload.strip()))
    return queries


def main() -> int:
    src = Path(sys.argv[1] if len(sys.argv) > 1 else "joern/out/report-tds.md")
    if not src.exists():
        print(f"no report at {src} — run: make joern-scan", file=sys.stderr)
        return 1
    out = src.with_name(src.name.replace("report-", "review-"))
    queries = parse(src)

    lines = [
        f"# Joern review worklist — {src.name}",
        "",
        "Generated by `joern/review.py`. One checkbox per **question**, not per hit:",
        "hits with the same expression shape in the same file are one item, with every",
        "location listed. Tick an item when it has been read and judged; record the",
        "verdict next to it so the next pass does not repeat the reading.",
        "",
        "Verdicts used below: **OK-by-construction** (the guard or the type makes it",
        "safe), **OK-deliberate** (correct on purpose, worth a comment in the source),",
        "**LOOK** (needs an argument from someone who knows the protocol), **BUG**.",
        "",
    ]

    total_items = 0
    for qid, q in queries.items():
        hits = q["hits"]
        lines += [f"## {qid} — {q['title']}", "", f"{len(hits)} hits"]
        if not hits:
            lines += ["", "- [x] nothing to review", ""]
            continue

        if qid in INVENTORY:
            by_file = OrderedDict()
            for f, ln, _ in hits:
                by_file.setdefault(f, []).append(ln)
            lines += ["", "Inventory, not findings — reviewed by asking whether the list is",
                      "complete and whether anything on it is unexpected.", ""]
            for f, lns in sorted(by_file.items(), key=lambda kv: -len(kv[1])):
                lines.append(f"- `{f}` — {len(lns)} method(s)")
            lines.append("")
            continue

        groups = OrderedDict()
        for f, ln, payload in hits:
            groups.setdefault((f, normalise(payload)), []).append((ln, payload))
        lines += ["", f"{len(groups)} item(s) to review", ""]
        for (f, shape), occurrences in groups.items():
            total_items += 1
            locs = ", ".join(ln for ln, _ in occurrences)
            n = f" ×{len(occurrences)}" if len(occurrences) > 1 else ""
            lines.append(f"- [ ] **`{f}`**{n} — `{shape}`")
            lines.append(f"      lines {locs}")
            sample = occurrences[0][1]
            if sample != shape:
                lines.append(f"      e.g. `{sample}`")
            lines.append("      verdict: ")
        lines.append("")

    lines += ["---", "", f"{total_items} reviewable items across the non-inventory queries.", ""]
    out.write_text("\n".join(lines))
    print(f"{out}  ({total_items} items)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
